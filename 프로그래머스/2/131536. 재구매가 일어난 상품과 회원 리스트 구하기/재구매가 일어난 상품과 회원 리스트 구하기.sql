SELECT USER_ID, PRODUCT_ID FROM 
    (SELECT USER_ID, PRODUCT_ID, COUNT(*) C
    FROM ONLINE_SALE
    GROUP BY USER_ID, PRODUCT_ID) B
WHERE C > 1
ORDER BY USER_ID ASC, PRODUCT_ID DESC